-- V3: Append-only custody log with hash chaining, scoped per evidence item.
--
-- FK is ON DELETE SET NULL, not CASCADE or RESTRICT:
--   - RESTRICT would block the existing Phase I deleteEvidence() flow, since
--     every evidence row gets an UPLOADED custody record immediately on
--     creation — that would break working functionality, not acceptable.
--   - CASCADE would destroy audit history on delete, defeating the purpose
--     of the feature.
-- Instead, evidence_original_filename and evidence_sha256_hash are captured
-- as a snapshot at log-write time, so the record stays meaningful even if
-- evidence_id later becomes null.
--
-- No update/delete is expected against this table from application code —
-- enforced at the service layer (see CustodyLogServiceImpl), not by a DB
-- constraint. Revisit with a DB-level grant restriction if stronger
-- guarantees are needed later.

CREATE TABLE custody_log (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidence_id                 BIGINT,
    evidence_original_filename  VARCHAR(255),
    evidence_sha256_hash        VARCHAR(255),
    action                      VARCHAR(255) NOT NULL,
    performed_by                VARCHAR(255) NOT NULL,
    timestamp                   TIMESTAMP(6) NOT NULL,
    remarks                     VARCHAR(2000),
    previous_hash               VARCHAR(255),
    current_hash                VARCHAR(255) NOT NULL,

    CONSTRAINT fk_custody_evidence
        FOREIGN KEY (evidence_id) REFERENCES evidence(id)
        ON DELETE SET NULL
);

CREATE INDEX idx_custody_evidence_id ON custody_log (evidence_id);