-- V4: Investigator-to-case assignment, many-to-many via join entity
-- (not a plain join table) so assignment carries audit metadata
-- (assigned_by, assigned_at). Metadata only — does not change any
-- existing authorization rule; any investigator can still view/act on
-- any case as before. See CaseInvestigatorServiceImpl.

CREATE TABLE case_investigators (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id         BIGINT NOT NULL,
    investigator_id BIGINT NOT NULL,
    assigned_by     VARCHAR(255) NOT NULL,
    assigned_at     TIMESTAMP(6) NOT NULL,

    CONSTRAINT fk_ci_case
        FOREIGN KEY (case_id) REFERENCES investigation_cases(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_ci_investigator
        FOREIGN KEY (investigator_id) REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_case_investigator UNIQUE (case_id, investigator_id)
);

CREATE INDEX idx_ci_case_id ON case_investigators (case_id);
CREATE INDEX idx_ci_investigator_id ON case_investigators (investigator_id);