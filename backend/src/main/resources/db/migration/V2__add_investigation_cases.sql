-- V2: Introduces investigation_cases and wires evidence.case_id to it as a
-- real foreign key. investigation_cases must be created before the ALTER,
-- since the FK constraint references it.
CREATE SEQUENCE case_number_seq START WITH 1 INCREMENT BY 1;
CREATE TABLE investigation_cases (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_number   VARCHAR(255) NOT NULL UNIQUE,
    title         VARCHAR(255) NOT NULL,
    description   VARCHAR(2000),
    status        VARCHAR(255) NOT NULL,
    created_by    VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP(6),
    updated_at    TIMESTAMP(6)
);

ALTER TABLE evidence
    ADD CONSTRAINT fk_evidence_case
    FOREIGN KEY (case_id) REFERENCES investigation_cases(id)
    ON DELETE SET NULL;

CREATE INDEX idx_evidence_case_id ON evidence (case_id);
CREATE INDEX idx_case_status ON investigation_cases (status);