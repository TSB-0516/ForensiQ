-- V1: Baseline schema, matching User.java and Evidence.java exactly as of
-- Phase I completion. investigation_case intentionally excluded — it will
-- be introduced as a proper, designed migration when Phase II's
-- InvestigationCase entity is built, not inherited from an earlier
-- undocumented auto-DDL artifact.

CREATE TABLE IF NOT EXISTS users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(255),
    email       VARCHAR(255) UNIQUE,
    password    VARCHAR(255),
    role        VARCHAR(255),
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS evidence (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    additional_remarks    VARCHAR(2000),
    collected_by          VARCHAR(255),
    collection_date       DATE,
    collection_location   VARCHAR(255),
    collection_time       TIME(0),
    description           VARCHAR(2000),
    evidence_type         VARCHAR(255),
    file_size_bytes       BIGINT,
    investigation_tags    VARCHAR(255),
    original_filename     VARCHAR(255),
    registered            BOOLEAN NOT NULL,
    related_suspect       VARCHAR(255),
    related_witness       VARCHAR(255),
    sha256_hash           VARCHAR(255),
    storage_path          VARCHAR(255),
    stored_filename       VARCHAR(255),
    title                 VARCHAR(255),
    upload_timestamp      TIMESTAMP(6),
    uploaded_by           VARCHAR(255),
    case_id               BIGINT
);

CREATE INDEX IF NOT EXISTS idx_evidence_type ON evidence (evidence_type);